/**
 * vision-qa.ts — Visual QA via e2e video recording + GPT-4o Vision
 *
 * Pipeline: run Playwright e2e tests with video → ffmpeg extract frames → GPT-4o → report
 */

import { execSync } from 'node:child_process';
import {
  mkdirSync,
  existsSync,
  readdirSync,
  readFileSync,
  writeFileSync,
  rmSync,
  statSync,
} from 'node:fs';
import path from 'node:path';
import { log } from '../utils/logger.js';
import { VISION_QA_ANALYSIS_TEMPLATE } from '../prompts/repository.js';
import { appendPromptModelCallTrace } from '../prompts/runtime-trace.js';
import { formatBrowserUnavailableEvidence, isPlaywrightBrowserUnavailable } from './browser-readiness.js';

// ─── Types ──────────────────────────────────────────────────

export interface VisionTestResult {
  testFile: string;
  testName: string;
  passed: boolean;
  framePaths: string[];
  visionVerdict?: 'pass' | 'fail' | 'inconclusive';
  visionConfidence?: number;
  visionSummary?: string;
  criteriaResults?: Array<{
    criterion: string;
    met: boolean;
    evidence: string;
  }>;
  cost?: number;
  error?: string;
}

export interface VisionQAReport {
  status: 'completed' | 'infra_unavailable' | 'skipped';
  timestamp: string;
  totalTests: number;
  playwrightPassed: number;
  visionPassed: number;
  visionFailed: number;
  totalCost: number;
  results: VisionTestResult[];
  /** Markdown summary for feeding into Controller prompt */
  summary: string;
}

export interface VisionQAOptions {
  projectDir: string;
  baseUrl?: string;
  healthCheckUrl: string;
  openaiApiKey: string;
  openaiBaseUrl?: string;
  workDir: string;
  model?: string;
  fps?: number;
  maxFramesPerTest?: number;
  /** Test seam. Production uses the project-local Playwright test command with platform browser readiness. */
  playwrightCommandRunner?: (command: string, options: any) => unknown;
}

// ─── Helpers ────────────────────────────────────────────────

function discoverE2ETests(projectDir: string): string[] {
  const e2eDir = path.join(projectDir, 'e2e');
  if (!existsSync(e2eDir)) return [];
  return readdirSync(e2eDir)
    .filter(f => f.endsWith('.spec.ts'))
    .sort()
    .map(f => path.join(e2eDir, f));
}

function extractFrames(videoPath: string, framesDir: string, fps: number): string[] {
  mkdirSync(framesDir, { recursive: true });
  const pattern = path.join(framesDir, 'frame_%04d.png');
  try {
    execSync(`ffmpeg -i "${videoPath}" -vf "fps=${fps}" -q:v 2 "${pattern}" -y 2>/dev/null`, {
      stdio: 'pipe',
      timeout: 30_000,
    });
  } catch {
    return [];
  }
  return readdirSync(framesDir)
    .filter(f => f.startsWith('frame_') && f.endsWith('.png'))
    .sort()
    .map(f => path.join(framesDir, f));
}

function collectVideos(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const videos: string[] = [];
  const walk = (d: string) => {
    for (const entry of readdirSync(d)) {
      const full = path.join(d, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry.endsWith('.webm') || entry.endsWith('.mp4')) videos.push(full);
    }
  };
  walk(dir);
  return videos.sort();
}

function selectFrames(paths: string[], max: number): string[] {
  if (paths.length <= max) return paths;
  const step = (paths.length - 1) / (max - 1);
  const selected: string[] = [];
  for (let i = 0; i < max; i++) selected.push(paths[Math.round(i * step)]);
  return selected;
}

function taskNameFromFile(specFile: string): string {
  return path.basename(specFile, '.spec.ts').replace('e2e-', '').replace(/-/g, ' ');
}

/**
 * Generate a JS Playwright config inside projectDir (uses project's own @playwright/test).
 */
function generatePlaywrightConfig(projectDir: string, outputDir: string): string {
  const configPath = path.join(projectDir, '_qa-vision-pw.config.js');
  const testDir = JSON.stringify(path.join(projectDir, 'e2e'));
  const resultsFile = JSON.stringify(path.join(outputDir, 'results.json'));
  const artifactsDir = JSON.stringify(path.join(outputDir, 'test-artifacts'));

  writeFileSync(configPath, `// Auto-generated by ralph vision-qa — safe to delete
const { defineConfig } = require('@playwright/test');
module.exports = defineConfig({
  testDir: ${testDir},
  timeout: 8 * 60 * 1000,
  retries: 0,
  workers: 1,
  reporter: [['json', { outputFile: ${resultsFile} }]],
  use: {
    video: { mode: 'on', size: { width: 1280, height: 720 } },
    trace: 'off',
    screenshot: 'on',
    viewport: { width: 1280, height: 720 },
  },
  outputDir: ${artifactsDir},
});
`, 'utf-8');
  return configPath;
}

// ─── Vision API call ────────────────────────────────────────

interface VisionApiResult {
  verdict: 'pass' | 'fail' | 'inconclusive';
  confidence: number;
  summary: string;
  criteriaResults: Array<{ criterion: string; met: boolean; evidence: string }>;
  inputTokens: number;
  outputTokens: number;
  cost: number;
}

async function callVisionApi(
  framePaths: string[],
  taskDescription: string,
  criteria: string[],
  workDir: string,
  apiKey: string,
  baseUrl: string | undefined,
  model: string,
  maxFrames: number,
): Promise<VisionApiResult> {
  // Dynamic import — openai may or may not be installed
  const { default: OpenAI } = await import('openai');

  const selected = selectFrames(framePaths, maxFrames);
  const content: any[] = [];

  const criteriaText = criteria.map((c, i) => `  ${i + 1}. ${c}`).join('\n');
  const promptText = `${VISION_QA_ANALYSIS_TEMPLATE}\n\n## Task: ${taskDescription}\n\n## Acceptance Criteria\n${criteriaText}`;
  content.push({
    type: 'text',
    text: promptText,
  });

  for (let i = 0; i < selected.length; i++) {
    if (!existsSync(selected[i])) continue;
    const data = readFileSync(selected[i]).toString('base64');
    content.push({ type: 'text', text: `\n--- Frame ${i + 1}/${selected.length} ---` });
    content.push({ type: 'image_url', image_url: { url: `data:image/png;base64,${data}`, detail: 'high' } });
  }

  const client = new OpenAI({
    apiKey,
    ...(baseUrl ? { baseURL: baseUrl } : {}),
  });
  let response;
  try {
    response = await client.chat.completions.create({
      model,
      max_tokens: 2048,
      messages: [{ role: 'user', content }],
    });
  } catch (err: any) {
    await recordVisionQAPromptTrace(workDir, promptText, err.message, false, model, {
      status: 'error',
      summary: err.message,
      frameCount: selected.length,
      criteriaCount: criteria.length,
    });
    throw err;
  }

  const rawText = response.choices[0]?.message?.content || '';
  const inputTokens = response.usage?.prompt_tokens || 0;
  const outputTokens = response.usage?.completion_tokens || 0;
  // GPT-4o: $2.50/MTok in, $10/MTok out
  const cost = (inputTokens * 2.5 + outputTokens * 10) / 1_000_000;

  let parsed: any;
  try {
    const m = rawText.match(/```json\s*([\s\S]*?)```/) || rawText.match(/(\{[\s\S]*\})/);
    if (!m) throw new Error('No JSON');
    parsed = JSON.parse(m[1]);
  } catch {
    await recordVisionQAPromptTrace(workDir, promptText, rawText, true, model, {
      status: 'error',
      summary: 'failed to parse vision response',
      frameCount: selected.length,
      criteriaCount: criteria.length,
    });
    return { verdict: 'inconclusive', confidence: 0, summary: 'Failed to parse vision response', criteriaResults: [], inputTokens, outputTokens, cost };
  }

  await recordVisionQAPromptTrace(workDir, promptText, rawText, true, model, {
    status: 'ok',
    summary: `verdict=${parsed.verdict || 'inconclusive'}; confidence=${parsed.confidence || 0}; criteriaResults=${Array.isArray(parsed.criteriaResults) ? parsed.criteriaResults.length : 0}`,
    frameCount: selected.length,
    criteriaCount: criteria.length,
  });

  return {
    verdict: parsed.verdict || 'inconclusive',
    confidence: parsed.confidence || 0,
    summary: parsed.summary || '',
    criteriaResults: parsed.criteriaResults || [],
    inputTokens,
    outputTokens,
    cost,
  };
}

// ─── Main pipeline ──────────────────────────────────────────

const DEFAULT_CRITERIA = [
  'The web page loads and renders content',
  'UI elements (buttons, forms, navigation) are visible and functional',
  'If game canvas is shown: game elements are rendered correctly',
  'If game canvas is shown: game appears interactive and physics-enabled',
  'No obvious crashes, blank screens, or error messages visible',
  'The application flow progresses normally',
];

export async function runVisionQA(opts: VisionQAOptions): Promise<VisionQAReport> {
  const {
    projectDir,
    baseUrl,
    healthCheckUrl,
    openaiApiKey,
    openaiBaseUrl,
    workDir,
    model = 'gpt-4o',
    fps = 2,
    maxFramesPerTest = 8,
    playwrightCommandRunner = execSync,
  } = opts;

  const outputDir = path.join(workDir, '.ralph', 'vision-qa', `run-${Date.now()}`);
  mkdirSync(outputDir, { recursive: true });

  const specs = discoverE2ETests(projectDir);
  if (specs.length === 0) {
    log.warn('Vision QA: no e2e tests found, skipping');
    return emptyReport();
  }

  log.info(`Vision QA: running ${specs.length} e2e tests with video recording...`);

  // 1. Generate PW config and run tests
  const pwConfig = generatePlaywrightConfig(projectDir, outputDir);
  const resolvedBaseUrl = baseUrl || new URL('/', healthCheckUrl).toString().replace(/\/$/, '');

  try {
    playwrightCommandRunner(`npx playwright test --config="${path.basename(pwConfig)}"`, {
      cwd: projectDir,
      encoding: 'utf-8',
      env: { ...process.env, HEALTH_CHECK_URL: healthCheckUrl, BASE_URL: resolvedBaseUrl },
      timeout: 15 * 60 * 1000,
      stdio: 'pipe',
    });
  } catch (err: any) {
    if (isPlaywrightBrowserUnavailable(err)) {
      const evidence = formatBrowserUnavailableEvidence(err);
      log.warn(`Vision QA skipped: ${evidence}`);
      return browserUnavailableReport(specs, evidence);
    }
    // Playwright exits non-zero if tests fail — expected
  } finally {
    rmSync(pwConfig, { force: true });
  }

  // 2. Parse PW results
  const resultsPath = path.join(outputDir, 'results.json');
  let pwResults: any = { suites: [] };
  if (existsSync(resultsPath)) {
    try { pwResults = JSON.parse(readFileSync(resultsPath, 'utf-8')); } catch { /* ignore */ }
  }

  const testStatuses: Array<{ title: string; ok: boolean }> = [];
  const flattenSuites = (suites: any[]) => {
    for (const s of suites || []) {
      for (const spec of s.specs || []) testStatuses.push({ title: spec.title, ok: spec.ok });
      if (s.suites) flattenSuites(s.suites);
    }
  };
  flattenSuites(pwResults.suites || []);

  // 3. Collect videos
  const artifactsDir = path.join(outputDir, 'test-artifacts');
  const allVideos = collectVideos(artifactsDir);
  log.info(`Vision QA: ${allVideos.length} video(s) recorded, analyzing with ${model}...`);

  // 4. Analyze each video
  const results: VisionTestResult[] = [];
  let totalCost = 0;

  for (let i = 0; i < allVideos.length; i++) {
    const videoPath = allVideos[i];
    const framesDir = path.join(outputDir, 'frames', `test-${i}`);
    const framePaths = extractFrames(videoPath, framesDir, fps);

    const specFile = specs[i] || specs[0];
    const testName = taskNameFromFile(specFile);
    const pwPassed = testStatuses[i]?.ok ?? false;

    if (framePaths.length === 0) {
      results.push({ testFile: specFile, testName, passed: pwPassed, framePaths: [], error: 'No frames extracted' });
      continue;
    }

    try {
      const vis = await callVisionApi(framePaths, `E2E test: ${testName}`, DEFAULT_CRITERIA, workDir, openaiApiKey, openaiBaseUrl, model, maxFramesPerTest);
      totalCost += vis.cost;

      const icon = vis.verdict === 'pass' ? '✅' : vis.verdict === 'fail' ? '❌' : '❓';
      log.info(`  ${icon} ${testName}: ${vis.verdict} (${(vis.confidence * 100).toFixed(0)}%) — $${vis.cost.toFixed(4)}`);

      results.push({
        testFile: specFile,
        testName,
        passed: pwPassed,
        framePaths,
        visionVerdict: vis.verdict,
        visionConfidence: vis.confidence,
        visionSummary: vis.summary,
        criteriaResults: vis.criteriaResults,
        cost: vis.cost,
      });
    } catch (err: any) {
      log.warn(`  ⚠️ Vision API error for ${testName}: ${err.message}`);
      results.push({ testFile: specFile, testName, passed: pwPassed, framePaths, error: err.message });
    }
  }

  const report = buildReport(results, totalCost);

  // Save report
  const reportPath = path.join(outputDir, 'vision-report.json');
  writeFileSync(reportPath, JSON.stringify(report, null, 2));
  log.info(`Vision QA: report saved → ${reportPath}`);
  log.info(`Vision QA: ${report.visionPassed} pass / ${report.visionFailed} fail — $${totalCost.toFixed(4)}`);

  return report;
}

async function recordVisionQAPromptTrace(
  workDir: string,
  prompt: string,
  output: string,
  success: boolean,
  model: string,
  parse: {
    status: 'ok' | 'error';
    summary: string;
    frameCount: number;
    criteriaCount: number;
  },
): Promise<void> {
  try {
    await appendPromptModelCallTrace(workDir, {
      promptId: 'visionQA.analysis',
      owner: 'vision-qa',
      label: 'Visual QA frame analysis',
      prompt,
      result: { success, output },
      model,
      parse: {
        status: parse.status,
        summary: parse.summary,
      },
      context: {
        frameCount: parse.frameCount,
        criteriaCount: parse.criteriaCount,
      },
    });
  } catch (err: any) {
    log.warn(`Vision QA: failed to write prompt trace: ${err.message}`);
  }
}

// ─── Report builders ────────────────────────────────────────

function buildReport(results: VisionTestResult[], totalCost: number): VisionQAReport {
  const playwrightPassed = results.filter(r => r.passed).length;
  const visionPassed = results.filter(r => r.visionVerdict === 'pass').length;
  const visionFailed = results.filter(r => r.visionVerdict === 'fail').length;

  return {
    status: 'completed',
    timestamp: new Date().toISOString(),
    totalTests: results.length,
    playwrightPassed,
    visionPassed,
    visionFailed,
    totalCost,
    results,
    summary: buildSummary(results, totalCost),
  };
}

function buildSummary(results: VisionTestResult[], totalCost: number): string {
  const lines: string[] = ['## Visual QA Report (GPT-4o Vision)', ''];

  for (const r of results) {
    const pw = r.passed ? 'PASS' : 'FAIL';
    const vis = r.visionVerdict
      ? `${r.visionVerdict.toUpperCase()} (${((r.visionConfidence ?? 0) * 100).toFixed(0)}%)`
      : r.error || 'skipped';

    lines.push(`### ${r.testName}`);
    lines.push(`- Playwright: ${pw} | Vision: ${vis}`);
    if (r.visionSummary) lines.push(`- ${r.visionSummary}`);
    if (r.criteriaResults) {
      for (const cr of r.criteriaResults) {
        lines.push(`  - ${cr.met ? '✅' : '❌'} ${cr.criterion}: ${cr.evidence}`);
      }
    }
    lines.push('');
  }

  lines.push(`Cost: $${totalCost.toFixed(4)}`);
  return lines.join('\n');
}

function emptyReport(): VisionQAReport {
  return {
    status: 'skipped',
    timestamp: new Date().toISOString(),
    totalTests: 0,
    playwrightPassed: 0,
    visionPassed: 0,
    visionFailed: 0,
    totalCost: 0,
    results: [],
    summary: '## Visual QA Report\nNo e2e tests found — skipped.',
  };
}

function browserUnavailableReport(specs: string[], evidence: string): VisionQAReport {
  const results = specs.map((specFile) => ({
    testFile: specFile,
    testName: taskNameFromFile(specFile),
    passed: false,
    framePaths: [],
    error: evidence,
  }));

  return {
    status: 'infra_unavailable',
    timestamp: new Date().toISOString(),
    totalTests: results.length,
    playwrightPassed: 0,
    visionPassed: 0,
    visionFailed: 0,
    totalCost: 0,
    results,
    summary: [
      '## Visual QA Report',
      evidence,
      '',
      'Browser verification infrastructure is platform-owned; no project-local browser install was attempted.',
    ].join('\n'),
  };
}
