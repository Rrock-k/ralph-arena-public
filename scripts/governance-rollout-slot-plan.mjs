#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  normalizeSiteAddress,
  normalizeSlotId,
  normalizeUpstream,
  renderActiveUpstreamCaddy,
} from "./governance-rollout-router-config.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scriptPath = fileURLToPath(import.meta.url);
const allowedSchedulerRoles = new Set(["standby", "external"]);
const allowedMigrationStatuses = new Set(["compatible", "not_required"]);
const envValuePattern = /^[A-Za-z0-9._:/@+-]+$/;

export function buildSlotRolloutPlan(options = {}) {
  const slotId = normalizeSlotId(options.slotId);
  const port = normalizeSlotPort(options.port);
  const releaseSha = normalizeEnvValue(options.releaseSha, "release sha");
  const buildId = normalizeEnvValue(options.buildId, "build id");
  const previousRef = normalizeEnvValue(options.previousRef, "previous ref");
  const migrationStatus = normalizeEnum(options.migrationStatus, allowedMigrationStatuses, "migration status");
  const schedulerRole = normalizeEnum(options.schedulerRole, allowedSchedulerRoles, "scheduler role");
  const siteAddress = normalizeSiteAddress(options.siteAddress);
  const appDir = normalizeAbsolutePath(options.appDir, "app dir");
  const upstream = normalizeUpstream(options.upstream ?? `127.0.0.1:${port}`);
  const readinessUrl = normalizeUrl(options.readinessUrl ?? `http://127.0.0.1:${port}/api/readiness`, "readiness url");
  const generatedAt = options.generatedAt ?? new Date().toISOString();
  const slotEnvRelativePath = `ops/governance-slots/${slotId}.env`;
  const activeUpstreamRelativePath = `ops/governance-rollout/Caddyfile.${slotId}.candidate`;

  const slotEnv = renderSlotEnv({
    slotId,
    port,
    releaseSha,
    buildId,
    migrationStatus,
    schedulerRole,
  });
  const activeUpstreamCaddy = renderActiveUpstreamCaddy({
    slotId,
    upstream,
    siteAddress,
  });

  return {
    taskId: "RA-344",
    mode: "slot-rollout-plan",
    generatedAt,
    operator: "scripts/governance-rollout-slot-plan.mjs",
    nonIntervention: true,
    decision: "prepared",
    release: {
      sha: releaseSha,
      buildId,
      previousRef,
      migrationStatus,
    },
    slot: {
      id: slotId,
      port,
      upstream,
      readinessUrl,
      schedulerRole,
      envPath: path.posix.join(appDir, slotEnvRelativePath),
    },
    router: {
      siteAddress,
      candidatePath: path.posix.join(appDir, activeUpstreamRelativePath),
      activeUpstreamOwner: "caddy-template",
    },
    artifacts: {
      slotEnv,
      activeUpstreamCaddy,
    },
    commands: buildCommandPlan({
      appDir,
      slotId,
      previousRef,
      readinessUrl,
      schedulerRole,
      siteAddress,
      slotEnvRelativePath,
      activeUpstreamRelativePath,
      upstream,
    }),
  };
}

export function writeSlotRolloutArtifacts(plan, outDir) {
  const absoluteOutDir = path.resolve(repoRoot, outDir);
  const slotEnvPath = path.join(absoluteOutDir, "slot.env");
  const caddyPath = path.join(absoluteOutDir, "Caddyfile.active-upstream");
  const reportPath = path.join(absoluteOutDir, "slot-rollout-plan.json");

  fs.mkdirSync(absoluteOutDir, { recursive: true });
  fs.writeFileSync(slotEnvPath, plan.artifacts.slotEnv);
  fs.writeFileSync(caddyPath, plan.artifacts.activeUpstreamCaddy);
  fs.writeFileSync(reportPath, `${JSON.stringify(withoutInlineArtifacts(plan), null, 2)}\n`);

  return {
    outDir: absoluteOutDir,
    slotEnvPath,
    caddyPath,
    reportPath,
  };
}

export function renderSlotEnv(options) {
  return [
    "# Generated by scripts/governance-rollout-slot-plan.mjs",
    "# Copy to ops/governance-slots/<slot>.env before starting governance-web@<slot>.",
    `PORT=${options.port}`,
    `APP_PORT=${options.port}`,
    "HOSTNAME=0.0.0.0",
    `GOVERNANCE_SLOT_ID=${options.slotId}`,
    `GOVERNANCE_SCHEDULER_ROLE=${options.schedulerRole}`,
    `GOVERNANCE_BUILD_ID=${options.buildId}`,
    `GOVERNANCE_RELEASE_SHA=${options.releaseSha}`,
    `GOVERNANCE_MIGRATION_STATUS=${options.migrationStatus}`,
    "",
  ].join("\n");
}

function buildCommandPlan(options) {
  const shellAppDir = shellQuote(options.appDir);
  const reportDir = `work/rollouts/governance-production/${options.slotId}`;
  return [
    {
      id: "migration-gate",
      mutates: false,
      command:
        `cd ${shellAppDir} && node scripts/governance-rollout-preflight.mjs --static --migration-gate --previous-ref ${shellQuote(options.previousRef)}`,
    },
    {
      id: "build-release",
      mutates: true,
      command:
        `cd ${shellAppDir} && npm --prefix packages/contracts ci && npm --prefix packages/contracts run build && npm --prefix packages/ralph-core ci && npm --prefix packages/ralph-core run build && npm --prefix apps/governance-platform ci && npm --prefix apps/governance-platform run db:generate && npm --prefix apps/governance-platform run build`,
    },
    {
      id: "install-slot-env",
      mutates: true,
      command:
        `install -d -m 0755 ${shellQuote(`${options.appDir}/ops/governance-slots`)} && install -m 0640 slot.env ${shellQuote(`${options.appDir}/${options.slotEnvRelativePath}`)}`,
    },
    {
      id: "start-standby-slot",
      mutates: true,
      command: `systemctl daemon-reload && systemctl start governance-web@${options.slotId}`,
    },
    {
      id: "canary-standby",
      mutates: false,
      command:
        `cd ${shellAppDir} && node scripts/governance-rollout-canary.mjs --url ${shellQuote(options.readinessUrl)} --slot ${options.slotId} --scheduler-role ${options.schedulerRole} --report ${shellQuote(`${reportDir}/canary-standby.json`)}`,
    },
    {
      id: "render-active-upstream",
      mutates: true,
      command:
        `cd ${shellAppDir} && node scripts/governance-rollout-router-config.mjs --slot ${options.slotId} --upstream ${shellQuote(options.upstream)} --site-address ${shellQuote(options.siteAddress)} --out ${shellQuote(options.activeUpstreamRelativePath)}`,
    },
    {
      id: "promote-active-upstream",
      mutates: true,
      command:
        "caddy validate --config <candidate-caddyfile> && install -m 0644 <candidate-caddyfile> /etc/caddy/Caddyfile && systemctl reload caddy",
    },
    {
      id: "rollback-active-upstream",
      mutates: true,
      command:
        "install -m 0644 <previous-caddyfile> /etc/caddy/Caddyfile && systemctl reload caddy",
    },
  ];
}

function withoutInlineArtifacts(plan) {
  return {
    ...plan,
    artifacts: {
      slotEnvBytes: Buffer.byteLength(plan.artifacts.slotEnv, "utf8"),
      activeUpstreamCaddyBytes: Buffer.byteLength(plan.artifacts.activeUpstreamCaddy, "utf8"),
    },
  };
}

function normalizeSlotPort(value) {
  const raw = `${value ?? ""}`.trim();
  if (!/^[0-9]+$/.test(raw)) {
    throw new Error("port is required and must be numeric");
  }
  const port = Number(raw);
  if (!Number.isInteger(port) || port < 1024 || port > 65535) {
    throw new Error("port must be an integer from 1024 to 65535");
  }
  if (port === 3000) {
    throw new Error("port 3000 is reserved for the active governance entrypoint");
  }
  return port;
}

function normalizeEnum(value, allowed, name) {
  const normalized = normalizeEnvValue(value, name);
  if (!allowed.has(normalized)) {
    throw new Error(`${name} must be one of: ${[...allowed].join(", ")}`);
  }
  return normalized;
}

function normalizeEnvValue(value, name) {
  const normalized = `${value ?? ""}`.trim();
  if (!normalized) {
    throw new Error(`${name} is required`);
  }
  if (!envValuePattern.test(normalized)) {
    throw new Error(`${name} contains unsupported characters`);
  }
  return normalized;
}

function normalizeAbsolutePath(value, name) {
  const normalized = `${value ?? ""}`.trim();
  if (!normalized) {
    throw new Error(`${name} is required`);
  }
  if (!path.posix.isAbsolute(normalized)) {
    throw new Error(`${name} must be an absolute path`);
  }
  if (normalized.includes("\n") || normalized.includes("'")) {
    throw new Error(`${name} contains unsupported characters`);
  }
  return normalized.replace(/\/+$/, "");
}

function normalizeUrl(value, name) {
  const normalized = `${value ?? ""}`.trim();
  if (!normalized) {
    throw new Error(`${name} is required`);
  }
  let parsed;
  try {
    parsed = new URL(normalized);
  } catch {
    throw new Error(`${name} must be a valid URL`);
  }
  if (!["http:", "https:"].includes(parsed.protocol)) {
    throw new Error(`${name} must use http or https`);
  }
  if (!parsed.port) {
    throw new Error(`${name} must include an explicit port`);
  }
  if (parsed.pathname !== "/api/readiness") {
    throw new Error(`${name} must target /api/readiness`);
  }
  if (parsed.search || parsed.hash) {
    throw new Error(`${name} must not include query or hash`);
  }
  return parsed.toString();
}

function shellQuote(value) {
  return `'${String(value).replaceAll("'", "'\\''")}'`;
}

function parseArgs(argv) {
  const parsed = {
    appDir: null,
    buildId: null,
    migrationStatus: null,
    outDir: null,
    port: null,
    previousRef: null,
    releaseSha: null,
    schedulerRole: null,
    siteAddress: null,
    slotId: null,
    upstream: null,
    readinessUrl: null,
    json: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--app-dir") {
      parsed.appDir = argv[++index];
    } else if (arg === "--build-id") {
      parsed.buildId = argv[++index];
    } else if (arg === "--migration-status") {
      parsed.migrationStatus = argv[++index];
    } else if (arg === "--out-dir") {
      parsed.outDir = argv[++index];
    } else if (arg === "--port") {
      parsed.port = argv[++index];
    } else if (arg === "--previous-ref") {
      parsed.previousRef = argv[++index];
    } else if (arg === "--release-sha") {
      parsed.releaseSha = argv[++index];
    } else if (arg === "--scheduler-role") {
      parsed.schedulerRole = argv[++index];
    } else if (arg === "--site-address") {
      parsed.siteAddress = argv[++index];
    } else if (arg === "--slot") {
      parsed.slotId = argv[++index];
    } else if (arg === "--upstream") {
      parsed.upstream = argv[++index];
    } else if (arg === "--readiness-url") {
      parsed.readinessUrl = argv[++index];
    } else if (arg === "--json") {
      parsed.json = true;
    } else if (arg === "--help" || arg === "-h") {
      parsed.help = true;
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }

  return parsed;
}

function printHelp() {
  console.log(`Usage: node scripts/governance-rollout-slot-plan.mjs --slot <blue|green> --port <port> --release-sha <sha> --build-id <id> --previous-ref <ref> --migration-status <compatible|not_required> --scheduler-role <standby|external> --site-address <addr> --app-dir <abs-path> [options]

Options:
  --out-dir <path>        Write slot.env, Caddyfile.active-upstream, and plan JSON.
  --upstream <origin>     Override upstream origin. Defaults to 127.0.0.1:<port>.
  --readiness-url <url>   Override standby readiness URL. Defaults to http://127.0.0.1:<port>/api/readiness.
  --json                  Print full plan JSON.
`);
}

function main() {
  try {
    const args = parseArgs(process.argv.slice(2));
    if (args.help) {
      printHelp();
      return;
    }
    const plan = buildSlotRolloutPlan(args);
    const written = args.outDir ? writeSlotRolloutArtifacts(plan, args.outDir) : null;
    const output = written ? { ...withoutInlineArtifacts(plan), written } : withoutInlineArtifacts(plan);

    if (args.json) {
      console.log(JSON.stringify(output, null, 2));
    } else {
      console.log(`RA-344 governance slot rollout plan: ${plan.decision}`);
      console.log(`slot: ${plan.slot.id}`);
      console.log(`port: ${plan.slot.port}`);
      console.log(`readiness: ${plan.slot.readinessUrl}`);
      if (written) console.log(`report: ${written.reportPath}`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  main();
}
