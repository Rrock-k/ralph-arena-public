#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scriptPath = fileURLToPath(import.meta.url);
const envNamePattern = /^[A-Z][A-Z0-9_]*$/;
const safeTokenPattern = /^[A-Za-z0-9._:/@_+-]+$/;

export function buildDbSafetyPlan(options = {}) {
  const databaseUrlEnv = normalizeEnvName(options.databaseUrlEnv ?? "DATABASE_URL", "database url env");
  const scratchDatabaseUrlEnv = normalizeEnvName(
    options.scratchDatabaseUrlEnv ?? "SCRATCH_DATABASE_URL",
    "scratch database url env",
  );
  const backupPath = normalizeAbsolutePath(options.backupPath, "backup path");
  const appDir = normalizeAbsolutePath(options.appDir, "app dir");
  const releaseSha = normalizeEnvValue(options.releaseSha, "release sha");
  const previousRef = normalizeEnvValue(options.previousRef, "previous ref");
  const generatedAt = options.generatedAt ?? new Date().toISOString();
  const backupReportPath = path.posix.join(appDir, "work/rollouts/governance-production/db-backup.json");
  const scratchRestoreReportPath = path.posix.join(appDir, "work/rollouts/governance-production/scratch-restore.json");
  const backupScript = renderBackupScript({
    backupPath,
    databaseUrlEnv,
    backupReportPath,
    releaseSha,
    previousRef,
  });
  const scratchRestoreScript = renderScratchRestoreScript({
    backupPath,
    scratchDatabaseUrlEnv,
    scratchRestoreReportPath,
    releaseSha,
    previousRef,
  });

  return {
    taskId: "RA-344",
    mode: "db-safety-plan",
    generatedAt,
    operator: "scripts/governance-rollout-db-safety-plan.mjs",
    nonIntervention: true,
    release: {
      sha: releaseSha,
      previousRef,
    },
    inputs: {
      databaseUrlEnv,
      scratchDatabaseUrlEnv,
      backupPath,
      appDir,
    },
    expectedReports: {
      backup: backupReportPath,
      scratchRestore: scratchRestoreReportPath,
    },
    commands: [
      {
        id: "db-backup",
        mutates: false,
        command: `bash db-backup-execution.sh`,
      },
      {
        id: "scratch-restore",
        mutates: true,
        command: `bash scratch-restore-execution.sh`,
      },
    ],
    artifacts: {
      backupScript,
      scratchRestoreScript,
    },
    decision: "prepared",
  };
}

export function writeDbSafetyArtifacts(plan, outDir) {
  const absoluteOutDir = path.resolve(repoRoot, outDir);
  const planPath = path.join(absoluteOutDir, "db-safety-plan.json");
  const backupScriptPath = path.join(absoluteOutDir, "db-backup-execution.sh");
  const scratchRestoreScriptPath = path.join(absoluteOutDir, "scratch-restore-execution.sh");
  const summaryPath = path.join(absoluteOutDir, "db-safety-summary.md");

  fs.mkdirSync(absoluteOutDir, { recursive: true });
  fs.writeFileSync(planPath, `${JSON.stringify(withoutInlineArtifacts(plan), null, 2)}\n`);
  fs.writeFileSync(backupScriptPath, plan.artifacts.backupScript, { mode: 0o755 });
  fs.writeFileSync(scratchRestoreScriptPath, plan.artifacts.scratchRestoreScript, { mode: 0o755 });
  fs.writeFileSync(summaryPath, renderSummary(plan));

  return {
    outDir: absoluteOutDir,
    planPath,
    backupScriptPath,
    scratchRestoreScriptPath,
    summaryPath,
  };
}

function renderBackupScript(options) {
  return [
    "#!/usr/bin/env bash",
    "set -euo pipefail",
    "",
    "# Generated by scripts/governance-rollout-db-safety-plan.mjs for RA-344 DB backup evidence.",
    "# The generator is non-intervention; running this script reads the configured database and writes backup evidence.",
    "",
    `: "\${${options.databaseUrlEnv}:?${options.databaseUrlEnv} is required}"`,
    `backup_path=${shellQuote(options.backupPath)}`,
    `report_path=${shellQuote(options.backupReportPath)}`,
    "install -d -m 0755 \"$(dirname \"$backup_path\")\"",
    "install -d -m 0755 \"$(dirname \"$report_path\")\"",
    `pg_dump --format=custom --no-owner --no-acl --file "$backup_path" "\${${options.databaseUrlEnv}}"`,
    "sha256=$(sha256sum \"$backup_path\" | awk '{print $1}')",
    "generated_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)",
    "cat > \"$report_path\" <<JSON",
    "{",
    "  \"taskId\": \"RA-344\",",
    "  \"mode\": \"db-backup\",",
    "  \"generatedAt\": \"$generated_at\",",
    "  \"operator\": \"db-backup-execution.sh\",",
    "  \"nonIntervention\": true,",
    "  \"decision\": \"passed\",",
    "  \"release\": {",
    `    "sha": "${options.releaseSha}",`,
    `    "previousRef": "${options.previousRef}"`,
    "  },",
    "  \"artifact\": {",
    "    \"path\": \"$backup_path\",",
    "    \"sha256\": \"$sha256\"",
    "  },",
    "  \"source\": {",
    `    "database": "${options.databaseUrlEnv}"`,
    "  }",
    "}",
    "JSON",
    "echo \"RA-344 DB backup evidence: $report_path\" >&2",
    "",
  ].join("\n");
}

function renderScratchRestoreScript(options) {
  return [
    "#!/usr/bin/env bash",
    "set -euo pipefail",
    "",
    "# Generated by scripts/governance-rollout-db-safety-plan.mjs for RA-344 scratch restore evidence.",
    "# The generator is non-intervention; running this script mutates only the configured scratch database.",
    "",
    `: "\${${options.scratchDatabaseUrlEnv}:?${options.scratchDatabaseUrlEnv} is required}"`,
    `backup_path=${shellQuote(options.backupPath)}`,
    `report_path=${shellQuote(options.scratchRestoreReportPath)}`,
    "test -f \"$backup_path\"",
    "install -d -m 0755 \"$(dirname \"$report_path\")\"",
    "sha256=$(sha256sum \"$backup_path\" | awk '{print $1}')",
    `pg_restore --clean --if-exists --no-owner --no-acl --dbname "\${${options.scratchDatabaseUrlEnv}}" "$backup_path"`,
    `psql "\${${options.scratchDatabaseUrlEnv}}" -v ON_ERROR_STOP=1 -c "select 1" >/dev/null`,
    "generated_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)",
    "cat > \"$report_path\" <<JSON",
    "{",
    "  \"taskId\": \"RA-344\",",
    "  \"mode\": \"scratch-restore\",",
    "  \"generatedAt\": \"$generated_at\",",
    "  \"operator\": \"scratch-restore-execution.sh\",",
    "  \"nonIntervention\": true,",
    "  \"decision\": \"passed\",",
    "  \"release\": {",
    `    "sha": "${options.releaseSha}",`,
    `    "previousRef": "${options.previousRef}"`,
    "  },",
    "  \"sourceBackupSha256\": \"$sha256\",",
    "  \"target\": {",
    "    \"kind\": \"scratch-postgres\",",
    `    "database": "${options.scratchDatabaseUrlEnv}"`,
    "  },",
    "  \"restore\": {",
    "    \"status\": \"passed\"",
    "  }",
    "}",
    "JSON",
    "echo \"RA-344 scratch restore evidence: $report_path\" >&2",
    "",
  ].join("\n");
}

function withoutInlineArtifacts(plan) {
  return {
    ...plan,
    artifacts: {
      backupScriptBytes: Buffer.byteLength(plan.artifacts.backupScript, "utf8"),
      scratchRestoreScriptBytes: Buffer.byteLength(plan.artifacts.scratchRestoreScript, "utf8"),
    },
  };
}

function renderSummary(plan) {
  return [
    "# RA-344 DB Safety Plan",
    "",
    `Decision: ${plan.decision}`,
    `Release: ${plan.release.sha}`,
    `Previous ref: ${plan.release.previousRef}`,
    "",
    "Evidence reports:",
    `- ${plan.expectedReports.backup}`,
    `- ${plan.expectedReports.scratchRestore}`,
    "",
    "Execution scripts:",
    "- db-backup-execution.sh",
    "- scratch-restore-execution.sh",
    "",
  ].join("\n");
}

function normalizeEnvName(value, name) {
  const normalized = `${value ?? ""}`.trim();
  if (!envNamePattern.test(normalized)) {
    throw new Error(`${name} must be an uppercase environment variable name`);
  }
  return normalized;
}

function normalizeEnvValue(value, name) {
  const normalized = `${value ?? ""}`.trim();
  if (!normalized) {
    throw new Error(`${name} is required`);
  }
  if (!safeTokenPattern.test(normalized)) {
    throw new Error(`${name} contains unsupported characters`);
  }
  return normalized;
}

function normalizeAbsolutePath(value, name) {
  const normalized = `${value ?? ""}`.trim();
  if (!normalized || !path.posix.isAbsolute(normalized) || normalized.includes("\0")) {
    throw new Error(`${name} must be an absolute POSIX path`);
  }
  if (!safeTokenPattern.test(normalized)) {
    throw new Error(`${name} contains unsupported characters`);
  }
  return normalized.replace(/\/+$/, "") || "/";
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

function parseArgs(argv) {
  const parsed = {
    appDir: null,
    backupPath: null,
    databaseUrlEnv: "DATABASE_URL",
    generatedAt: null,
    outDir: null,
    previousRef: null,
    releaseSha: null,
    scratchDatabaseUrlEnv: "SCRATCH_DATABASE_URL",
    json: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--app-dir") {
      parsed.appDir = argv[++index];
    } else if (arg === "--backup-path") {
      parsed.backupPath = argv[++index];
    } else if (arg === "--database-url-env") {
      parsed.databaseUrlEnv = argv[++index];
    } else if (arg === "--generated-at") {
      parsed.generatedAt = argv[++index];
    } else if (arg === "--out-dir") {
      parsed.outDir = argv[++index];
    } else if (arg === "--previous-ref") {
      parsed.previousRef = argv[++index];
    } else if (arg === "--release-sha") {
      parsed.releaseSha = argv[++index];
    } else if (arg === "--scratch-database-url-env") {
      parsed.scratchDatabaseUrlEnv = argv[++index];
    } else if (arg === "--json") {
      parsed.json = true;
    } else if (arg === "--help" || arg === "-h") {
      parsed.help = true;
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }

  return parsed;
}

function printHelp() {
  console.log(`Usage: node scripts/governance-rollout-db-safety-plan.mjs --app-dir <abs-path> --backup-path <abs-path> --release-sha <sha> --previous-ref <ref> --out-dir <path> [options]

Options:
  --database-url-env <name>          Env var containing production database URL. Default: DATABASE_URL.
  --scratch-database-url-env <name>  Env var containing scratch database URL. Default: SCRATCH_DATABASE_URL.
  --generated-at <iso>               Fixed timestamp for deterministic tests.
  --json                             Print full plan JSON.
`);
}

function main() {
  try {
    const args = parseArgs(process.argv.slice(2));
    if (args.help) {
      printHelp();
      return;
    }
    if (!args.outDir) throw new Error("--out-dir is required");

    const plan = buildDbSafetyPlan(args);
    const written = writeDbSafetyArtifacts(plan, args.outDir);
    const output = { ...withoutInlineArtifacts(plan), written };

    if (args.json) {
      console.log(JSON.stringify(output, null, 2));
    } else {
      console.log(`RA-344 DB safety plan: ${plan.decision}`);
      console.log(`backup report: ${plan.expectedReports.backup}`);
      console.log(`scratch restore report: ${plan.expectedReports.scratchRestore}`);
      console.log(`plan: ${written.planPath}`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  main();
}
