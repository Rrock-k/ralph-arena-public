/**
 * Self-contained interstitial HTML page served by preview-gate (via Caddy forward_auth)
 * when the user hasn't consented to viewing third-party AI-generated content.
 *
 * The page sets a consent cookie and reloads — on reload the gate sees the cookie and allows through.
 */

export function buildInterstitialHtml(opts: {
  isSecure: boolean;
  requiresAuth?: boolean;
  loginUrl?: string;
}): string {
  const { isSecure, requiresAuth, loginUrl } = opts;
  const securePart = isSecure ? " Secure;" : "";

  const checkbox = `<label style="display:flex;align-items:start;gap:8px;margin-top:20px;cursor:pointer;text-align:left">
    <input type="checkbox" id="ack" onchange="document.getElementById('go').disabled=!this.checked" style="margin-top:2px;accent-color:#10b981;width:16px;height:16px;flex-shrink:0">
    <span style="font-size:12px;color:#94a3b8;line-height:1.5">I understand this content is generated by an AI agent and has not been reviewed or endorsed by Ralph Arena</span>
  </label>`;

  const authMessage = requiresAuth
    ? `<p style="margin-top:12px;color:#f59e0b">Sign in required to view this preview.</p>
       ${checkbox}
       <a id="go" href="${escapeHtml(loginUrl ?? "/")}" onclick="if(!document.getElementById('ack').checked){event.preventDefault()}" style="display:inline-block;margin-top:16px;padding:10px 24px;background:#2563eb;color:#fff;border-radius:8px;text-decoration:none;font-weight:600;font-size:14px;opacity:0.4;pointer-events:auto;transition:opacity .15s">Sign in</a>
       <style>#ack:checked~*~#go,#go[disabled]{opacity:1!important}#go:not([disabled]):hover{opacity:0.9!important}</style>`
    : `${checkbox}
       <button id="go" onclick="consent()" disabled style="margin-top:16px;padding:10px 32px;background:#10b981;color:#fff;border:none;border-radius:8px;cursor:pointer;font-weight:600;font-size:14px;transition:opacity .15s;opacity:0.4">Continue</button>
       <style>#go:disabled{cursor:not-allowed}#go:not(:disabled){opacity:1!important}#go:not(:disabled):hover{background:#059669!important}</style>`;

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Preview — Ralph Arena</title>
<style>
*{margin:0;padding:0;box-sizing:border-box}
body{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;background:#0b0f19;color:#e2e8f0;display:flex;align-items:center;justify-content:center;min-height:100vh;padding:24px}
.card{max-width:440px;text-align:center;padding:40px 32px;border:1px solid #1e293b;border-radius:16px;background:#111827}
.logo{font-size:20px;font-weight:700;letter-spacing:-.5px;margin-bottom:24px;color:#fff}
.logo span{color:#10b981}
.icon{margin:0 auto 20px;width:48px;height:48px;border-radius:50%;background:#1e293b;display:flex;align-items:center;justify-content:center}
.icon svg{width:24px;height:24px;stroke:#f59e0b;fill:none}
h1{font-size:18px;font-weight:600;margin-bottom:12px}
p{font-size:13px;line-height:1.6;color:#94a3b8}
a:hover{text-decoration:none}
.sub{margin-top:16px;font-size:11px;color:#475569}
</style>
</head>
<body>
<div class="card">
  <div class="logo">Ralph <span>Arena</span></div>
  <div class="icon">
    <svg viewBox="0 0 24 24" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
      <path d="M10.29 3.86L1.82 18a2 2 0 001.71 3h16.94a2 2 0 001.71-3L13.71 3.86a2 2 0 00-3.42 0z"/>
      <line x1="12" y1="9" x2="12" y2="13"/>
      <line x1="12" y1="17" x2="12.01" y2="17"/>
    </svg>
  </div>
  <h1>AI-Generated Content</h1>
  <p>This preview was built by an AI agent. The content is sandboxed but not reviewed. Ralph Arena is not responsible for what's inside.</p>
  ${authMessage}
  <p class="sub">This warning appears once per preview.</p>
</div>
<script>
function consent(){document.cookie="arena_consent=1; path=/; max-age=86400; SameSite=Lax;${securePart}";location.reload()}
</script>
</body>
</html>`;
}

/**
 * RA-055: Human-readable error page for preview auth failures.
 * Replaces raw "Access denied" text responses.
 */
export function buildErrorHtml(opts: {
  title: string;
  message: string;
  loginUrl?: string;
}): string {
  const { title, message, loginUrl } = opts;
  const actionButton = loginUrl
    ? `<a href="${escapeHtml(loginUrl)}" style="display:inline-block;margin-top:20px;padding:10px 24px;background:#3b82f6;color:#fff;border-radius:8px;text-decoration:none;font-weight:500;font-size:14px;transition:background .15s">Sign in</a>`
    : "";

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${escapeHtml(title)} — Ralph Arena</title>
<style>
*{margin:0;padding:0;box-sizing:border-box}
body{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;background:#0b0f19;color:#e2e8f0;display:flex;align-items:center;justify-content:center;min-height:100vh;padding:24px}
.card{max-width:400px;text-align:center;padding:40px 32px;border:1px solid #1e293b;border-radius:16px;background:#111827}
.logo{font-size:20px;font-weight:700;letter-spacing:-.5px;margin-bottom:24px;color:#fff}
.logo span{color:#10b981}
h1{font-size:18px;font-weight:600;margin-bottom:12px}
p{font-size:13px;line-height:1.6;color:#94a3b8}
</style>
</head>
<body>
<div class="card">
  <div class="logo">Ralph <span>Arena</span></div>
  <h1>${escapeHtml(title)}</h1>
  <p>${escapeHtml(message)}</p>
  ${actionButton}
</div>
</body>
</html>`;
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
